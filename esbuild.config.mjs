import esbuild from "esbuild";
import process from "process";
import { builtinModules } from "node:module";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { compile, preprocess } from "svelte/compiler";

const notices = readFileSync('THIRD_PARTY_NOTICES.md', 'utf8').replace(/\*\//g, '* /');
const banner = `/*!
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Decision Matrix - MIT License, copyright (c) 2026 Lennart Friebel.
See LICENSE in the source repository for the plugin license.

${notices}
*/
`;

const prod = process.argv[2] === "production";

const sveltePlugin = {
	name: "svelte5-esbuild",
	setup(build) {
		build.onLoad({ filter: /\.svelte$/ }, async (args) => {
			const source = readFileSync(args.path, "utf8");
			const preprocessed = await preprocess(source, {
				script: async ({ content, attributes }) => {
					if (attributes.lang === "ts") {
						const res = await esbuild.transform(content, {
							loader: "ts",
							target: "es2020",
							tsconfigRaw: {
								compilerOptions: {
									verbatimModuleSyntax: true
								}
							}
						});
						return { code: res.code };
					}
					return { code: content };
				}
			});
			const compiled = compile(preprocessed.code, {
				filename: args.path,
				generate: "client",
				css: "injected"
			});
			return {
				contents: compiled.js.code,
				loader: "js"
			};
		});
	}
};

const context = await esbuild.context({
	banner: {
		js: banner
	},
	entryPoints: ["main.ts"],
	bundle: true,
	plugins: [sveltePlugin],
	conditions: ["svelte", "browser", "import", "default"],
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules
	],
	format: "cjs",
	target: "es2020",
	logLevel: "info",
	sourcemap: false,
	treeShaking: true,
	outfile: "main.js",
	metafile: true,
	minify: prod
});

if (prod) {
	const result = await context.rebuild();
	mkdirSync('dist', { recursive: true });
	writeFileSync('dist/build-metafile.json', JSON.stringify(result.metafile, null, 2));
	await context.dispose();
} else {
	await context.watch();
}
